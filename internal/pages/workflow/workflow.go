// Package workflow builds a reviewable GitHub Actions workflow without I/O.
// Builds run on GitHub-hosted runners; the edge only receives their artifacts.
package workflow

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"net/url"
	"path"
	"regexp"
	"strings"
	"text/template"

	"github.com/ozal-project/ozal/internal/config"
)

// OperatorRevision is a published, immutable source revision with the native
// check/pack/deploy/accept commands. Never generate a mutable @main install.
const OperatorRevision = "900003e224c785f698ec015945b43fb2456753fd"

type Request struct {
	Project    string `json:"project"`
	Repository string `json:"repository"`
	Ref        string `json:"ref"`
	Filename   string `json:"filename"`
	Endpoint   string `json:"endpoint"`
	SiteURL    string `json:"site_url"`
	Directory  string `json:"directory"`
	Output     string `json:"output"`
}

type Plan struct {
	Request
	Base    string `json:"base"`
	Branch  string `json:"branch"`
	Path    string `json:"path"`
	Content string `json:"content"`
	Digest  string `json:"digest"`
}

var (
	label      = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)
	file       = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]{0,95}\.ya?ml$`)
	repository = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9][A-Za-z0-9_.-]*$`)
	localPath  = regexp.MustCompile(`^[A-Za-z0-9_./-]+$`)
	branch     = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_./-]*$`)
)

func Build(r Request) (Plan, error) {
	base := strings.TrimPrefix(r.Ref, "refs/heads/")
	if !label.MatchString(r.Project) || !repository.MatchString(r.Repository) || len(r.Repository) > 200 ||
		!file.MatchString(r.Filename) || strings.Contains(r.Filename, "..") ||
		base == r.Ref || len(base) > 200 || !branch.MatchString(base) || strings.Contains(base, "..") ||
		strings.Contains(base, "//") || strings.HasSuffix(base, "/") || strings.HasSuffix(base, ".") {
		return Plan{}, errors.New("valid project, repository, branch ref and workflow filename are required")
	}
	for _, part := range strings.Split(base, "/") {
		if strings.HasPrefix(part, ".") || strings.HasSuffix(part, ".lock") {
			return Plan{}, errors.New("invalid workflow branch")
		}
	}
	if err := config.ValidateProjectGitHubTrust(config.ProjectGitHubTrust{RepositoryID: 1, RepositoryOwnerID: 1, Ref: r.Ref, WorkflowRef: r.Repository + "/.github/workflows/" + r.Filename + "@" + r.Ref}); err != nil {
		return Plan{}, errors.New("invalid workflow trust")
	}
	for _, address := range []string{r.Endpoint, r.SiteURL} {
		u, err := url.Parse(address)
		if err != nil || len(address) > 512 || u.Scheme != "https" || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || u.Opaque != "" ||
			(u.Path != "" && u.Path != "/") || strings.Contains(address, "${{") || strings.ContainsAny(address, "\r\n\t\\") {
			return Plan{}, errors.New("deploy endpoint and site URL must be HTTPS origins")
		}
	}
	r.Endpoint = strings.TrimSuffix(r.Endpoint, "/")
	r.SiteURL = strings.TrimSuffix(r.SiteURL, "/")
	if !validPath(r.Directory, true) || !validPath(r.Output, false) {
		return Plan{}, errors.New("build directory and output must be relative paths without traversal or expressions")
	}
	data := struct {
		Request
		Base, Dist, Revision string
	}{r, base, path.Join(r.Directory, r.Output), OperatorRevision}
	tmpl, err := template.New("workflow").Delims("[[", "]]").Funcs(template.FuncMap{"quote": func(s string) string { b, _ := json.Marshal(s); return string(b) }}).Parse(source)
	if err != nil {
		return Plan{}, err
	}
	var content strings.Builder
	if err := tmpl.Execute(&content, data); err != nil {
		return Plan{}, err
	}
	sum := sha256.Sum256([]byte(content.String()))
	digest := hex.EncodeToString(sum[:])
	return Plan{Request: r, Base: base, Branch: "ozal/publish-" + r.Project + "-" + digest[:16], Path: ".github/workflows/" + r.Filename, Content: content.String(), Digest: digest}, nil
}

func validPath(s string, dot bool) bool {
	if s == "." {
		return dot
	}
	if len(s) == 0 || len(s) > 200 || !localPath.MatchString(s) || path.IsAbs(s) || path.Clean(s) != s {
		return false
	}
	for _, part := range strings.Split(s, "/") {
		if part == ".." || strings.HasPrefix(part, "-") || strings.HasPrefix(part, ".") {
			return false
		}
	}
	return true
}

